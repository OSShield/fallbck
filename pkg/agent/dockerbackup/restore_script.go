package dockerbackup

import (
	"fmt"
	"path"
	"sort"
	"strings"
	"time"

	dockerspec "github.com/osshield/fallbck/pkg/dockerbackup"
)

// containersFlag makes the script run the generated docker run commands
const containersFlag = "--containers"

// restoreSummary is the one-line description shown in the UI
func restoreSummary(m *dockerspec.Manifest, at time.Time) string {
	vols := 0
	for _, v := range m.Volumes {
		if v.Entry != "" {
			vols++
		}
	}
	return fmt.Sprintf("Docker %s host %s (%d containers, %d volumes archived, %d compose projects) taken %s; restore onto a host with Docker and compose installed using the generated script",
		orDash(m.Host.DockerVersion), m.Generator.Hostname, len(m.Containers), vols, len(m.Compose), at.Format(time.RFC3339))
}

// restoreCommands is the short runbook shown in the UI
func restoreCommands(m *dockerspec.Manifest, namespace string) []string {
	snapshot := fmt.Sprintf("%s/%s/%s", m.Snapshot.Type, m.Snapshot.ID, m.Snapshot.Time.UTC().Format("2006-01-02T15:04:05Z"))
	ns := ""
	if namespace != "" {
		ns = " --ns " + namespace
	}
	return []string{
		"# 1. Install Docker (and the compose plugin) on the new host, then fetch the archive with PBS credentials",
		"#    (fallbck-ctl targets credentials <target> prints these exports):",
		"export PBS_REPOSITORY='<token id>@<pbs host>:<datastore>' PBS_PASSWORD='<token secret>' PBS_FINGERPRINT='<sha256 fingerprint>'",
		fmt.Sprintf("proxmox-backup-client restore %s %s.pxar /var/tmp/fallbck-docker-restore%s", snapshot, dockerspec.ArchiveName, ns),
		"# 2. Review, then run the generated restore script (dry run first):",
		fmt.Sprintf("bash /var/tmp/fallbck-docker-restore/%s/%s --dry-run", dockerspec.CollectEntry, dockerspec.RestoreScriptName),
		fmt.Sprintf("bash /var/tmp/fallbck-docker-restore/%s/%s --yes            # add %s to also recreate standalone containers", dockerspec.CollectEntry, dockerspec.RestoreScriptName, containersFlag),
	}
}

// restoreScript renders the bash runbook stored in collect/. Like the PVE runbook it
// is plain and interactive: every step prints what it does, --dry-run only prints,
// --yes skips the confirmations. Steps: daemon.json, networks, volumes (create +
// copy the archived contents in with a helper container), images (load saved
// tarballs, pull references), compose projects (files back in place, compose up),
// standalone containers (generated docker run lines, executed only with --containers).
func restoreScript(m *dockerspec.Manifest, namespace, helperImage string) string {
	var b strings.Builder
	w := func(format string, args ...any) {
		fmt.Fprintf(&b, format, args...)
		b.WriteByte('\n')
	}
	snapshot := fmt.Sprintf("%s/%s/%s", m.Snapshot.Type, m.Snapshot.ID, m.Snapshot.Time.UTC().Format("2006-01-02T15:04:05Z"))
	w("#!/usr/bin/env bash")
	w("# FallBCK Docker host restore runbook, generated by fallbck-agent %s on %s", m.Generator.Version, m.Generator.Hostname)
	w("# Snapshot %s (job %q), taken %s", snapshot, m.Job.Name, m.Snapshot.Time.UTC().Format(time.RFC3339))
	w("#")
	w("# Run on a host with Docker (and the compose plugin) installed, as root, after")
	w("# restoring the archive:")
	w("#   proxmox-backup-client restore %s %s.pxar /var/tmp/fallbck-docker-restore%s", snapshot, dockerspec.ArchiveName, nsFlag(namespace))
	w("#   bash /var/tmp/fallbck-docker-restore/%s/%s --dry-run", dockerspec.CollectEntry, dockerspec.RestoreScriptName)
	w("#")
	w("# Options: --dry-run (print only), --yes (no confirmations), %s (also run the", containersFlag)
	w("# generated docker run commands for containers that are not part of a compose")
	w("# project; review them first), --restore-dir <dir> (default: the directory this")
	w("# script sits in, minus /%s), --helper-image <image> (default %s).", dockerspec.CollectEntry, helperImage)
	w("set -euo pipefail")
	w("")
	w("DRY=0; YES=0; CONTAINERS=0")
	w("HELPER_IMAGE=%s", shellQuote(helperImage))
	w("SCRIPT_DIR=\"$(cd \"$(dirname \"${BASH_SOURCE[0]}\")\" && pwd)\"")
	w("RESTORE_DIR=\"$(dirname \"$SCRIPT_DIR\")\"")
	w("while [ $# -gt 0 ]; do")
	w("  case \"$1\" in")
	w("    --dry-run) DRY=1 ;;")
	w("    --yes) YES=1 ;;")
	w("    %s) CONTAINERS=1 ;;", containersFlag)
	w("    --restore-dir) RESTORE_DIR=\"$2\"; shift ;;")
	w("    --helper-image) HELPER_IMAGE=\"$2\"; shift ;;")
	w("    *) echo \"unknown option $1\" >&2; exit 2 ;;")
	w("  esac")
	w("  shift")
	w("done")
	w("COLLECT=\"$RESTORE_DIR/%s\"", dockerspec.CollectEntry)
	w("")
	w("say() { printf '\\n==> %%s\\n' \"$*\"; }")
	w("run() { printf '   + %%s\\n' \"$*\"; [ \"$DRY\" = 1 ] || \"$@\"; }")
	w("confirm() { [ \"$YES\" = 1 ] && return 0; [ \"$DRY\" = 1 ] && return 0; read -r -p \"$1 [y/N] \" a; [ \"$a\" = y ] || [ \"$a\" = Y ]; }")
	w("")
	w("[ -d \"$COLLECT\" ] || { echo \"restore directory $RESTORE_DIR has no %s/ entry; pass --restore-dir\" >&2; exit 1; }", dockerspec.CollectEntry)
	w("command -v docker >/dev/null 2>&1 || { echo 'docker is not installed on this host' >&2; exit 1; }")
	w("docker version >/dev/null 2>&1 || { echo 'the Docker daemon is not running or not reachable' >&2; exit 1; }")
	w("if docker info --format '{{.Swarm.LocalNodeState}}' 2>/dev/null | grep -q '^active$'; then echo 'this host is an active Swarm node; this runbook restores standalone containers only' >&2; exit 1; fi")
	w("say \"Restoring Docker host %s (snapshot %s) from $RESTORE_DIR\"", m.Generator.Hostname, snapshot)
	w("[ \"$DRY\" = 1 ] && echo '   (dry run: nothing is changed)'")

	// 1. daemon.json
	w("")
	w("# ---- 1. Daemon configuration ------------------------------------------------")
	if m.Daemon.Archived {
		w("say 'Daemon configuration'")
		w("if confirm 'Restore %s and restart the Docker daemon?'; then", m.Daemon.ConfigPath)
		w("  run mkdir -p %s", shellQuote(path.Dir(m.Daemon.ConfigPath)))
		w("  run cp -a \"$COLLECT/daemon/daemon.json\" %s", shellQuote(m.Daemon.ConfigPath))
		w("  run systemctl restart docker || echo '   restart the Docker daemon by hand' >&2")
		w("fi")
	} else {
		w("say 'Daemon configuration: none was archived (defaults were in use)'")
	}

	// 2. networks
	w("")
	w("# ---- 2. Networks ------------------------------------------------------------")
	w("say 'Networks'")
	nets := 0
	for _, n := range m.Networks {
		if n.Builtin {
			continue
		}
		nets++
		args := []string{"docker", "network", "create"}
		if n.Driver != "" {
			args = append(args, "--driver", n.Driver)
		}
		if n.Internal {
			args = append(args, "--internal")
		}
		if n.Attachable {
			args = append(args, "--attachable")
		}
		if n.IPv6 {
			args = append(args, "--ipv6")
		}
		for _, s := range n.Subnets {
			if s.Subnet != "" {
				args = append(args, "--subnet", s.Subnet)
			}
			if s.Gateway != "" {
				args = append(args, "--gateway", s.Gateway)
			}
			if s.IPRange != "" {
				args = append(args, "--ip-range", s.IPRange)
			}
		}
		for _, k := range sortedKeys(n.Options) {
			args = append(args, "-o", k+"="+n.Options[k])
		}
		for _, k := range sortedKeys(n.Labels) {
			args = append(args, "--label", k+"="+n.Labels[k])
		}
		args = append(args, n.Name)
		w("if docker network inspect %s >/dev/null 2>&1; then echo '   network %s exists, kept'; else run %s; fi", shellQuote(n.Name), n.Name, quoteAll(args))
	}
	if nets == 0 {
		w("echo '   no user-defined networks'")
	}

	// 3. volumes
	w("")
	w("# ---- 3. Volumes -------------------------------------------------------------")
	w("say 'Volumes (create, then copy the archived contents in with a helper container)'")
	vols := 0
	for _, v := range m.Volumes {
		if v.Entry == "" {
			continue
		}
		vols++
		args := []string{"docker", "volume", "create"}
		if v.Driver != "" && v.Driver != "local" {
			args = append(args, "--driver", v.Driver)
		}
		for _, k := range sortedKeys(v.Options) {
			args = append(args, "-o", k+"="+v.Options[k])
		}
		for _, k := range sortedKeys(v.Labels) {
			args = append(args, "--label", k+"="+v.Labels[k])
		}
		args = append(args, v.Name)
		w("if docker volume inspect %s >/dev/null 2>&1; then", shellQuote(v.Name))
		w("  confirm 'Volume %s exists; overwrite its contents with the backup?' || { echo '   kept as is'; SKIP_%d=1; }", v.Name, vols)
		w("else")
		w("  run %s", quoteAll(args))
		w("fi")
		w("if [ \"${SKIP_%d:-0}\" != 1 ]; then", vols)
		w("  run docker run --rm -v %s:/vol -v \"$RESTORE_DIR/%s:/src:ro\" \"$HELPER_IMAGE\" sh -c 'cp -a /src/. /vol/'", shellQuote(v.Name), v.Entry)
		w("fi")
	}
	if vols == 0 {
		w("echo '   no volumes were archived'")
	}

	// 4. images
	w("")
	w("# ---- 4. Images --------------------------------------------------------------")
	w("say 'Images (load saved tarballs, pull references by digest)'")
	imgs := 0
	for _, im := range m.Images {
		imgs++
		if im.Saved != "" {
			w("run docker load -i \"$COLLECT/%s\"", im.Saved)
			continue
		}
		ref := ""
		if len(im.RepoDigests) > 0 {
			ref = im.RepoDigests[0]
		}
		tag := ""
		if len(im.RepoTags) > 0 {
			tag = im.RepoTags[0]
		}
		switch {
		case ref != "" && tag != "":
			w("run docker pull %s || run docker pull %s", shellQuote(ref), shellQuote(tag))
			w("run docker tag %s %s 2>/dev/null || true", shellQuote(ref), shellQuote(tag))
		case ref != "":
			w("run docker pull %s", shellQuote(ref))
		case tag != "":
			w("run docker pull %s", shellQuote(tag))
		default:
			w("echo '   image %s has no reference and was not saved (used by %s); rebuild it' >&2", shortID(strings.TrimPrefix(im.ID, "sha256:")), strings.Join(im.UsedBy, ", "))
		}
	}
	if imgs == 0 {
		w("echo '   no images recorded'")
	}

	// 5. compose projects
	w("")
	w("# ---- 5. Compose projects ----------------------------------------------------")
	w("say 'Compose projects (config files back in place, then compose up)'")
	if len(m.Compose) == 0 {
		w("echo '   no compose projects'")
	}
	for _, p := range m.Compose {
		w("say 'Project %s'", p.Name)
		if len(p.Archived) == 0 {
			w("echo '   no config files were archived for this project (see the manifest warnings); recreate it by hand' >&2")
			continue
		}
		for _, f := range p.Archived {
			w("run mkdir -p %s", shellQuote(path.Dir(f.Source)))
			w("if [ -e %s ] && ! cmp -s \"$COLLECT/%s\" %s; then", shellQuote(f.Source), f.File, shellQuote(f.Source))
			w("  confirm 'Overwrite %s with the archived copy?' && run cp -a \"$COLLECT/%s\" %s", f.Source, f.File, shellQuote(f.Source))
			w("else")
			w("  run cp -a \"$COLLECT/%s\" %s", f.File, shellQuote(f.Source))
			w("fi")
		}
		args := []string{"docker", "compose", "-p", p.Name}
		for _, f := range p.ConfigFiles {
			args = append(args, "-f", f)
		}
		args = append(args, "up", "-d")
		w("if confirm 'Start project %s now?'; then", p.Name)
		if p.WorkingDir != "" {
			w("  ( cd %s && run %s )", shellQuote(p.WorkingDir), quoteAll(args))
		} else {
			w("  run %s", quoteAll(args))
		}
		w("fi")
	}

	// 6. standalone containers
	w("")
	w("# ---- 6. Standalone containers -----------------------------------------------")
	w("say 'Standalone containers (not part of a compose project)'")
	standalone := 0
	for _, c := range m.Containers {
		if c.Skipped != "" || c.Project != "" {
			continue
		}
		standalone++
		cmd := dockerRunCommand(c)
		w("echo '   %s:'", c.Name)
		w("printf '     %%s\\n' %s", shellQuote(cmd))
		w("if [ \"$CONTAINERS\" = 1 ]; then")
		w("  if docker container inspect %s >/dev/null 2>&1; then echo '   container %s exists, kept'; else run %s; fi", shellQuote(c.Name), c.Name, cmd)
		w("fi")
	}
	if standalone == 0 {
		w("echo '   none'")
	} else {
		w("[ \"$CONTAINERS\" = 1 ] || echo '   (generated from docker inspect, best effort: review, then re-run with %s to create them)'", containersFlag)
	}
	if len(m.BindMounts) > 0 {
		w("")
		w("say 'Bind mounts used by containers are NOT part of this backup; restore them from the host filesystem backup:'")
		for _, bm := range m.BindMounts {
			w("echo '   %s (%s)'", bm.Source, strings.Join(bm.Containers, ", "))
		}
	}
	w("")
	w("say 'Done. Check: docker ps -a; docker compose ls'")
	return b.String()
}

// dockerRunCommand renders a best-effort docker run for a standalone container from
// the manifest entry (the full inspect document is in collect/ for anything missing)
func dockerRunCommand(c dockerspec.Container) string {
	args := []string{"docker", "run", "-d", "--name", c.Name}
	if c.Restart != "" && c.Restart != "no" {
		args = append(args, "--restart", c.Restart)
	}
	for _, m := range c.Mounts {
		switch m.Type {
		case "volume":
			spec := m.Volume + ":" + m.Destination
			if !m.RW {
				spec += ":ro"
			}
			args = append(args, "-v", spec)
		case "bind":
			spec := m.Source + ":" + m.Destination
			if !m.RW {
				spec += ":ro"
			}
			args = append(args, "-v", spec)
		case "tmpfs":
			args = append(args, "--tmpfs", m.Destination)
		}
	}
	for _, p := range c.Ports {
		spec := p.HostPort + ":" + p.ContainerPort
		if p.HostIP != "" && p.HostIP != "0.0.0.0" {
			spec = p.HostIP + ":" + spec
		}
		if p.Protocol != "" && p.Protocol != "tcp" {
			spec += "/" + p.Protocol
		}
		args = append(args, "-p", spec)
	}
	for _, n := range c.Networks {
		if n != "bridge" {
			args = append(args, "--network", n)
		}
	}
	for _, k := range sortedKeys(c.Labels) {
		if strings.HasPrefix(k, "com.docker.compose.") {
			continue
		}
		args = append(args, "--label", k+"="+c.Labels[k])
	}
	args = append(args, c.Image)
	return quoteAll(args)
}

func nsFlag(namespace string) string {
	if namespace == "" {
		return ""
	}
	return " --ns " + namespace
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// shellQuote single-quotes a value for bash
func shellQuote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\n'\"\\$`&|;<>()*?[]#~!{}") {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func quoteAll(args []string) string {
	out := make([]string, len(args))
	for i, a := range args {
		out[i] = shellQuote(a)
	}
	return strings.Join(out, " ")
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}
